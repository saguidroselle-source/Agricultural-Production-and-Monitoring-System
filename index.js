import express from 'express';
import path from 'path';
import fs from 'fs';
import session from 'express-session';
import dotenv from 'dotenv';
import Handlebars from 'handlebars';
import router from './routes/index.js';
dotenv.config();
const app=express();
const viewsDir=path.join(process.cwd(),'views');
app.use(express.json({limit:'1mb'}));
app.use(express.urlencoded({extended:true}));
app.use(express.static(path.join(process.cwd(),'public')));
app.use(session({secret:process.env.SESSION_SECRET||'replace-this-development-secret',resave:false,saveUninitialized:false,cookie:{httpOnly:true,sameSite:'lax',secure:process.env.NODE_ENV==='production',maxAge:8*60*60*1000}}));
// XianFire .xian templates use Handlebars syntax and support reusable partials.
const registerPartials=(dir,prefix='')=>{ for(const entry of fs.readdirSync(dir,{withFileTypes:true})){ const full=path.join(dir,entry.name); if(entry.isDirectory()) registerPartials(full,prefix?`${prefix}/${entry.name}`:entry.name); else if(entry.isFile()&&entry.name.endsWith('.xian')&&!prefix.startsWith('layouts')) { const key=(prefix?`${prefix}/`:'')+entry.name.replace(/\.xian$/,''); Handlebars.registerPartial(key,fs.readFileSync(full,'utf8')); } } };
registerPartials(viewsDir);
app.engine('xian',(filePath,options,callback)=>{ try { const source=fs.readFileSync(filePath,'utf8'); const template=Handlebars.compile(source); callback(null,template(options)); } catch(err) { callback(err); } });
app.set('views',viewsDir); app.set('view engine','xian');
app.use('/',router);
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:'An unexpected server error occurred.'});});
const port=process.env.PORT||3000;app.listen(port,()=>console.log(`AgriConnect running at http://localhost:${port}`));
